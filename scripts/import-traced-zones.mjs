/**
 * Import hand-traced zones from zones-traced.json (zone-tracer.html export).
 * Run: npm run import:zones
 */
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
import { readSnapConfig } from './lib/read-snap-config.mjs';
import {
  smoothTracedPath,
  symmetrizePoints,
  ellipseParamsFromPoints,
  ellipsePathFromParams,
  mirrorHorizontally,
  mirrorOpenChain,
  hairlineFromZone1Horns,
  DEFAULT_ZONE_SMOOTH,
} from './lib/path-smooth.mjs';
import {
  stitchZone4Boundaries,
  stitchZone4BorderStroke,
  stitchZone2Boundaries,
  stitchZone2BorderStroke,
  stitchZone1Horn,
} from './lib/stitch-zone-edges.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const INPUT_CANDIDATES = [
  join(root, 'zones-traced.json'),
  join(root, 'public', 'zones-traced.json'),
  join(__dirname, 'zones-traced.json'),
];

const LABEL_ANCHORS = {
  'zone-1': [{ x: 941, y: 848 }, { x: 1691, y: 848 }],
  'zone-2': [{ x: 1319, y: 848 }],
  'zone-3': [{ x: 1319, y: 715 }],
  'zone-4': [{ x: 1319, y: 525 }],
  'zone-5': [{ x: 1125, y: 232 }, { x: 1513, y: 232 }],
  'zone-6': [{ x: 1319, y: 217 }],
};

function findInput() {
  for (const p of INPUT_CANDIDATES) {
    if (existsSync(p)) return p;
  }
  return null;
}

function pointsToPath(points, closed) {
  if (!points?.length) return '';
  let d = `M ${points[0][0]} ${points[0][1]}`;
  for (let i = 1; i < points.length; i++) {
    d += ` L ${points[i][0]} ${points[i][1]}`;
  }
  if (closed !== false && points.length > 2) d += ' Z';
  return d;
}

function centroid(points) {
  if (!points?.length) return { x: 1319, y: 800 };
  const s = points.reduce((a, p) => ({ x: a.x + p[0], y: a.y + p[1] }), { x: 0, y: 0 });
  return { x: Math.round(s.x / points.length), y: Math.round(s.y / points.length) };
}

function mainTracedPath(zoneData) {
  const paths = zoneData?.paths ?? [];
  return paths.reduce(
    (best, p) => ((p.points?.length ?? 0) > (best?.points?.length ?? 0) ? p : best),
    paths[0],
  );
}

function buildTsOutput(snappedZones, labelPositions, smoothed, strokeOverlays = {}) {
  const zoneEntries = Object.entries(snappedZones)
    .map(([id, data]) => {
      const pathsStr = data.paths.map((p) => `      ${JSON.stringify(p)}`).join(',\n');
      const fillRule = data.fillRule ? `\n    fillRule: '${data.fillRule}' as const,` : '';
      return `  '${id}': {\n    paths: [\n${pathsStr},\n    ],${fillRule}\n  }`;
    })
    .join(',\n');

  const labelEntries = Object.entries(labelPositions)
    .map(([id, positions]) => {
      const posStr = positions.map((p) => `{ x: ${p.x}, y: ${p.y} }`).join(', ');
      return `  '${id}': [${posStr}]`;
    })
    .join(',\n');

  const strokeEntries = Object.entries(strokeOverlays)
    .map(([id, paths]) => {
      const pathsStr = paths.map((p) => `      ${JSON.stringify(p)}`).join(',\n');
      return `  '${id}': [\n${pathsStr},\n  ]`;
    })
    .join(',\n');

  const strokeBlock = strokeEntries
    ? `\nexport const ZONE_STROKE_OVERLAYS: Partial<Record<ZoneId, string[]>> = {\n${strokeEntries},\n};\n`
    : '\nexport const ZONE_STROKE_OVERLAYS: Partial<Record<ZoneId, string[]>> = {};\n';

  return `/* eslint-disable */
/** Auto-generated by scripts/import-traced-zones.mjs — hand-traced zones */
import type { ZoneId } from './types';

export interface SnappedZonePaths {
  paths: string[];
  fillRule?: 'evenodd' | 'nonzero';
}

export const SNAPPED_ZONE_PATHS: Record<ZoneId, SnappedZonePaths> = {
${zoneEntries},
};

export const SNAPPED_LABEL_POSITIONS: Record<ZoneId, { x: number; y: number }[]> = {
${labelEntries},
};
${strokeBlock}
export const SNAP_GENERATION_META = {
  generatedAt: '${new Date().toISOString()}',
  source: 'zones-traced.json',
  smoothed: ${smoothed},
  maxEdgeErrorPx: 0,
  totalSnappedPoints: 0,
} as const;
`;
}

const inputPath = findInput();
if (!inputPath) {
  console.error('Nie znaleziono zones-traced.json');
  console.error('Zapisz plik z zone-tracer.html w jednej z lokalizacji:');
  INPUT_CANDIDATES.forEach((p) => console.error('  -', p));
  process.exit(1);
}

console.log('Reading', inputPath);
const traced = JSON.parse(readFileSync(inputPath, 'utf8'));
const zones = traced.zones ?? traced;
const smoothCfg = readSnapConfig();

const snappedZones = {};
const labelPositions = {};
const strokeOverlays = {};

for (const [zoneId, zoneData] of Object.entries(zones)) {
  const paths = (zoneData.paths ?? [])
    .map((p) => {
      if (smoothCfg.SMOOTH_TRACED_PATHS) {
        return smoothTracedPath(p, {
          zoneId,
          tension: smoothCfg.SMOOTH_TENSION,
        });
      }
      return pointsToPath(p.points, p.closed);
    })
    .filter(Boolean);

  if (!paths.length) {
    console.warn(`Warning: ${zoneId} has no paths, skipping`);
    continue;
  }

  snappedZones[zoneId] = {
    paths,
    ...(zoneData.fillRule ? { fillRule: zoneData.fillRule } : {}),
  };

  const pathList = zoneData.paths ?? [];
  if (zoneId === 'zone-1' && pathList.length >= 2) {
    labelPositions[zoneId] = pathList.slice(0, 2).map((p) => centroid(p.points ?? []));
  } else if (zoneId === 'zone-5' && pathList.length >= 2) {
    labelPositions[zoneId] = pathList.slice(0, 2).map((p) => centroid(p.points ?? []));
  } else {
    const allPts = pathList.flatMap((p) => p.points ?? []);
    labelPositions[zoneId] = [centroid(allPts)];
  }
}

// Stitch zone-2 / zone-4 shared edges to zone-3 ellipse
const z3traced = mainTracedPath(zones['zone-3']);
if (snappedZones['zone-3'] && z3traced?.points?.length >= 3) {
  let z3pts = z3traced.points.map((p) => [p[0], p[1]]);
  if (DEFAULT_ZONE_SMOOTH['zone-3']?.symmetrize) z3pts = symmetrizePoints(z3pts);
  const ell = ellipseParamsFromPoints(z3pts);

  if (ell) {
    const ellipsePath = ellipsePathFromParams(ell);
    snappedZones['zone-3'].paths[0] = ellipsePath;
    strokeOverlays['zone-3'] = [ellipsePath];
    console.log('Zone-3 set to canonical ellipse');

    const z4traced = mainTracedPath(zones['zone-4'])?.points;
    if (z4traced?.length) {
      const preset = DEFAULT_ZONE_SMOOTH['zone-4'] ?? {};
      const smoothOpts = { simplify: preset.simplify, tension: preset.tension };
      const stitched = stitchZone4Boundaries(z4traced, ell, smoothOpts);
      if (stitched) {
        snappedZones['zone-4'].paths[0] = stitched;
        console.log('Stitched zone-4 top edge to zone-3 ellipse');
      }
      const border = stitchZone4BorderStroke(z4traced, ell, smoothOpts);
      if (border) strokeOverlays['zone-4'] = [border];
    }

    const z1paths = zones['zone-1']?.paths;
    const leftRaw = z1paths?.[0]?.points?.map((p) => [p[0], p[1]]) ?? null;
    let hairline = null;

    if (leftRaw?.length >= 3) {
      const z2hair = mainTracedPath(zones['zone-2'])?.points ?? [];
      const tracedHairMaxY = z2hair.reduce((m, p) => Math.max(m, p[1]), 0);
      hairline = hairlineFromZone1Horns(leftRaw, ell, tracedHairMaxY);
    }

    const z2traced = mainTracedPath(zones['zone-2'])?.points;
    if (z2traced?.length) {
      const preset = DEFAULT_ZONE_SMOOTH['zone-2'] ?? {};
      const stitched = stitchZone2Boundaries(
        z2traced,
        ell,
        { simplify: preset.simplify, tension: preset.tension },
        hairline,
      );
      if (stitched) {
        snappedZones['zone-2'].paths[0] = stitched;
        console.log('Stitched zone-2: ellipse seam + hairline aligned to zone-1');
      }
      const border = stitchZone2BorderStroke(
        z2traced,
        ell,
        { simplify: preset.simplify, tension: preset.tension },
        hairline,
      );
      if (border) strokeOverlays['zone-2'] = [border];
    }

    if (leftRaw?.length >= 3 && hairline) {
      const preset = DEFAULT_ZONE_SMOOTH['zone-1'] ?? {};
      const smoothOpts = { simplify: 0, tension: preset.tension };
      const leftOuter = leftRaw.slice(hairline.splitIdx);
      const rightOuter = mirrorOpenChain(leftOuter, ell.cx);

      snappedZones['zone-1'].paths[0] = stitchZone1Horn(hairline, leftOuter, 'left', smoothOpts);
      snappedZones['zone-1'].paths[1] = stitchZone1Horn(hairline, rightOuter, 'right', smoothOpts);
      labelPositions['zone-1'] = [
        centroid(leftRaw),
        centroid(mirrorHorizontally(leftRaw, ell.cx)),
      ];
      console.log('Stitched zone-1 horns to zone-2 hairline (symmetric)');
    }
  }
}

const outPath = join(root, 'lib', 'graft-calculator', 'snapped-paths.generated.ts');
writeFileSync(
  outPath,
  buildTsOutput(snappedZones, labelPositions, smoothCfg.SMOOTH_TRACED_PATHS, strokeOverlays),
);
console.log('Wrote', outPath);
console.log(
  'Zones imported:',
  Object.keys(snappedZones).join(', '),
  smoothCfg.SMOOTH_TRACED_PATHS ? '(smoothed)' : '(raw)',
);

try {
  const sharp = (await import('sharp')).default;
  const COLORS = {
    'zone-1': 'rgba(229,0,126,0.45)',
    'zone-2': 'rgba(117,31,94,0.4)',
    'zone-3': 'rgba(0,120,255,0.35)',
    'zone-4': 'rgba(0,180,120,0.35)',
    'zone-5': 'rgba(255,140,0,0.4)',
    'zone-6': 'rgba(255,220,0,0.45)',
  };
  const FILL_ONLY = new Set(['zone-2', 'zone-3', 'zone-4']);
  const fillPaths = Object.entries(snappedZones).flatMap(([zone, { paths, fillRule }]) =>
    paths.map((d) => {
      const rule = fillRule ? ` fill-rule="${fillRule}"` : '';
      const stroke = FILL_ONLY.has(zone) ? ' stroke="none"' : ' stroke="#751F5E" stroke-width="3" stroke-dasharray="10 8"';
      return `<path d="${d}" fill="${COLORS[zone]}"${stroke}${rule}/>`;
    }),
  );
  const strokePaths = Object.entries(strokeOverlays).flatMap(([zone, paths]) =>
    paths.map(
      (d) =>
        `<path d="${d}" fill="none" stroke="#751F5E" stroke-width="3" stroke-dasharray="10 8"/>`,
    ),
  );
  const paths = [...fillPaths, ...strokePaths].join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="2656" height="1600" viewBox="0 0 2656 1600">${paths}</svg>`;
  const base = await sharp(join(root, 'public', 'man.webp')).ensureAlpha().png().toBuffer();
  const overlay = await sharp(Buffer.from(svg)).png().toBuffer();
  const out = await sharp(base).composite([{ input: overlay, blend: 'over' }]).png().toBuffer();
  await sharp(out).toFile(join(root, 'public', 'debug-zones.png'));
  console.log('Wrote public/debug-zones.png');
} catch (e) {
  console.warn('Debug PNG skipped:', e.message);
}
