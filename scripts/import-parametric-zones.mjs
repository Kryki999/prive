/**
 * Import parametric zone map (zones-parametric.json) → snapped-paths.generated.ts
 * Run: npm run import:zones
 */
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
import { buildZoneMap, DEFAULT_ZONE_PARAMS, normalizeParams } from './lib/zone-geometry.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const geomSrc = readFileSync(join(__dirname, 'lib', 'zone-geometry.mjs'), 'utf8');
writeFileSync(
  join(root, 'public', 'js', 'zone-geometry.js'),
  geomSrc.replace("from './path-smooth.mjs'", "from './path-smooth.js'"),
  'utf8',
);

const INPUT_CANDIDATES = [
  join(root, 'public', 'zones-parametric.json'),
  join(root, 'zones-parametric.json'),
];

function findInput() {
  for (const p of INPUT_CANDIDATES) {
    if (existsSync(p)) return p;
  }
  return null;
}

function buildTsOutput(map) {
  const { zones, strokeOverlays, labels } = map;

  const zoneEntries = Object.entries(zones)
    .map(([id, data]) => {
      const pathsStr = data.paths.map((p) => `      ${JSON.stringify(p)}`).join(',\n');
      const fillRule = data.fillRule ? `\n    fillRule: '${data.fillRule}' as const,` : '';
      return `  '${id}': {\n    paths: [\n${pathsStr},\n    ],${fillRule}\n  }`;
    })
    .join(',\n');

  const labelEntries = Object.entries(labels)
    .map(([id, positions]) => {
      const posStr = positions.map((p) => `{ x: ${p.x}, y: ${p.y} }`).join(', ');
      return `  '${id}': [${posStr}]`;
    })
    .join(',\n');

  const strokeEntries = Object.entries(strokeOverlays)
    .map(([id, paths]) => {
      const pathsStr = paths.map((p) => `      ${JSON.stringify(p)}`).join(',\n');
      return `  '${id}': [\n${pathsStr},\n  ]`;
    })
    .join(',\n');

  return `/* eslint-disable */
/** Auto-generated by scripts/import-parametric-zones.mjs — parametric zone map */
import type { ZoneId } from './types';

export interface SnappedZonePaths {
  paths: string[];
  fillRule?: 'evenodd' | 'nonzero';
}

export const SNAPPED_ZONE_PATHS: Record<ZoneId, SnappedZonePaths> = {
${zoneEntries},
};

export const SNAPPED_LABEL_POSITIONS: Record<ZoneId, { x: number; y: number }[]> = {
${labelEntries},
};

export const ZONE_STROKE_OVERLAYS: Partial<Record<ZoneId, string[]>> = {
${strokeEntries},
};

export const SNAP_GENERATION_META = {
  generatedAt: '${new Date().toISOString()}',
  source: 'zones-parametric.json',
  smoothed: false,
  parametric: true,
  maxEdgeErrorPx: 0,
  totalSnappedPoints: 0,
} as const;
`;
}

const inputPath = findInput();
let params = DEFAULT_ZONE_PARAMS;

if (inputPath) {
  console.log('Reading', inputPath);
  const json = JSON.parse(readFileSync(inputPath, 'utf8'));
  params = normalizeParams({ ...DEFAULT_ZONE_PARAMS, ...json });
} else {
  console.log('No zones-parametric.json — using built-in defaults');
  const defaultPath = join(root, 'public', 'zones-parametric.json');
  writeFileSync(defaultPath, JSON.stringify(DEFAULT_ZONE_PARAMS, null, 2));
  console.log('Wrote', defaultPath);
}

const map = buildZoneMap(params);
const outPath = join(root, 'lib', 'graft-calculator', 'snapped-paths.generated.ts');
writeFileSync(outPath, buildTsOutput(map));
console.log('Wrote', outPath);

try {
  const sharp = (await import('sharp')).default;
  const COLORS = {
    'zone-1': 'rgba(229,0,126,0.45)',
    'zone-2': 'rgba(117,31,94,0.4)',
    'zone-3': 'rgba(0,120,255,0.35)',
    'zone-4': 'rgba(0,180,120,0.35)',
    'zone-5': 'rgba(255,140,0,0.4)',
    'zone-6': 'rgba(255,220,0,0.45)',
  };
  const FILL_ONLY = new Set(['zone-2', 'zone-3', 'zone-4', 'zone-5', 'zone-6']);
  const fillPaths = Object.entries(map.zones).flatMap(([zone, { paths, fillRule }]) =>
    paths.map((d) => {
      const rule = fillRule ? ` fill-rule="${fillRule}"` : '';
      const stroke = FILL_ONLY.has(zone) ? ' stroke="none"' : ' stroke="rgba(117,31,94,0.68)" stroke-width="5" stroke-dasharray="9 7"';
      return `<path d="${d}" fill="${COLORS[zone]}"${stroke}${rule}/>`;
    }),
  );
  const strokePaths = Object.entries(map.strokeOverlays).flatMap(([, paths]) =>
    paths.map((d) => `<path d="${d}" fill="none" stroke="rgba(117,31,94,0.68)" stroke-width="5" stroke-dasharray="9 7"/>`),
  );
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="2656" height="1600" viewBox="0 0 2656 1600">${[...fillPaths, ...strokePaths].join('')}</svg>`;
  const base = await sharp(join(root, 'public', 'man.webp')).ensureAlpha().png().toBuffer();
  const overlay = await sharp(Buffer.from(svg)).png().toBuffer();
  const out = await sharp(base).composite([{ input: overlay, blend: 'over' }]).png().toBuffer();
  await sharp(out).toFile(join(root, 'public', 'debug-zones.png'));
  console.log('Wrote public/debug-zones.png');
} catch (e) {
  console.warn('Debug PNG skipped:', e.message);
}
