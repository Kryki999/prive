/**
 * Snap outer zone edges to scalp profile (green dots from man.webp pixels).
 * Run: npm run generate:zones
 */
import sharp from 'sharp';
import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
import { scanScalpProfile, serializeProfile } from './lib/scalp-profile.mjs';
import { readSnapConfig } from './lib/read-snap-config.mjs';
import { transformPath, transformPoint, snapPathToProfile, pathBounds } from './lib/path-utils.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const CALIBRATION = {
  sourceCenterX: 156,
  targetCenterX: 1347,
  scaleY: 3.8,
  translateX: -28,
  translateY: 88,
};

const ZONE_SCALE_X = {
  'zone-1': 3,
  'zone-2': 2.78,
  'zone-3': 2.78,
  'zone-4': 3.05,
  'zone-5': 3.18,
  'zone-6': 3.1,
};

const LABEL_ANCHORS = {
  'zone-1': [
    { x: 30, y: 200 },
    { x: 280, y: 200 },
  ],
  'zone-2': [{ x: 156, y: 200 }],
  'zone-3': [{ x: 156, y: 165 }],
  'zone-4': [{ x: 156, y: 115 }],
  'zone-5': [
    { x: 95, y: 38 },
    { x: 217, y: 38 },
  ],
  'zone-6': [{ x: 156, y: 34 }],
};

const ZONE_COLORS = {
  'zone-1': 'rgba(229,0,126,0.4)',
  'zone-2': 'rgba(117,31,94,0.35)',
  'zone-3': 'rgba(0,120,255,0.3)',
  'zone-4': 'rgba(0,180,120,0.3)',
  'zone-5': 'rgba(255,140,0,0.35)',
  'zone-6': 'rgba(255,220,0,0.4)',
};

const snapConfig = readSnapConfig();
const clinicana = JSON.parse(readFileSync(join(__dirname, 'clinicana-paths.snapshot.json'), 'utf8'));

console.log('Scanning scalp profile from man.webp...');
const scalpData = await scanScalpProfile(join(root, 'public', 'man.webp'));
const profile = scalpData.profile;

const profileJson = JSON.stringify(serializeProfile(scalpData), null, 2);
writeFileSync(join(root, 'lib', 'graft-calculator', 'scalp-profile.generated.json'), profileJson);
writeFileSync(join(root, 'public', 'scalp-profile.generated.json'), profileJson);
console.log('Wrote scalp-profile.generated.json (lib + public)');
console.log('Scalp bounds:', scalpData.bounds);

const snappedZones = {};
const labelPositions = {};
let globalMaxError = 0;
let totalSnapped = 0;

for (const { zone, paths, fillRule } of clinicana) {
  const scaleX = ZONE_SCALE_X[zone];
  const shouldSnap = snapConfig.SNAP_ZONES.includes(zone);
  const snappedPaths = [];

  for (let pathIdx = 0; pathIdx < paths.length; pathIdx++) {
    const calibrated = transformPath(paths[pathIdx], CALIBRATION, scaleX);
    const snapThisPath =
      shouldSnap && !(zone === 'zone-5' && pathIdx !== snapConfig.ZONE5_SNAP_PATH_INDEX);

    if (snapThisPath) {
      const bounds = pathBounds(calibrated);
      const { path, maxEdgeError, snappedCount } = snapPathToProfile(
        calibrated,
        profile,
        snapConfig,
        Math.round(scalpData.bounds.centerX),
        { minY: bounds.minY, maxY: bounds.maxY },
      );
      snappedPaths.push(path);
      globalMaxError = Math.max(globalMaxError, maxEdgeError);
      totalSnapped += snappedCount;
      console.log(`  ${zone} path[${pathIdx}]: snapped ${snappedCount} points`);
    } else {
      snappedPaths.push(calibrated);
    }
  }

  snappedZones[zone] = { paths: snappedPaths, fillRule: fillRule ?? undefined };
  labelPositions[zone] = LABEL_ANCHORS[zone].map((p) => transformPoint(p, CALIBRATION, scaleX));
}

writeFileSync(
  join(root, 'lib', 'graft-calculator', 'snapped-paths.generated.ts'),
  buildTsOutput(snappedZones, labelPositions, globalMaxError, totalSnapped, scalpData.bounds),
);
console.log('Wrote lib/graft-calculator/snapped-paths.generated.ts');

console.log(`\nSnap complete: ${totalSnapped} points adjusted, max edge error ${globalMaxError}px`);

// Debug overlay
await writeDebugOverlay(scalpData, snappedZones);
console.log('Wrote public/debug-scalp-profile.png, public/debug-zones.png');

function buildTsOutput(zones, labels, maxError, snappedPts, bounds) {
  const zoneEntries = Object.entries(zones)
    .map(([id, data]) => {
      const pathsStr = data.paths.map((p) => `      ${JSON.stringify(p)}`).join(',\n');
      const fillRule = data.fillRule ? `\n    fillRule: '${data.fillRule}' as const,` : '';
      return `  '${id}': {\n    paths: [\n${pathsStr},\n    ],${fillRule}\n  }`;
    })
    .join(',\n');

  const labelEntries = Object.entries(labels)
    .map(([id, positions]) => {
      const posStr = positions.map((p) => `{ x: ${p.x}, y: ${p.y} }`).join(', ');
      return `  '${id}': [${posStr}]`;
    })
    .join(',\n');

  return `/* eslint-disable */
/** Auto-generated by scripts/snap-zone-edges.mjs — do not edit manually */
import type { ZoneId } from './types';

export interface SnappedZonePaths {
  paths: string[];
  fillRule?: 'evenodd' | 'nonzero';
}

export const SNAPPED_ZONE_PATHS: Record<ZoneId, SnappedZonePaths> = {
${zoneEntries},
};

export const SNAPPED_LABEL_POSITIONS: Record<ZoneId, { x: number; y: number }[]> = {
${labelEntries},
};

export const SNAP_GENERATION_META = {
  generatedAt: '${new Date().toISOString()}',
  maxEdgeErrorPx: ${maxError},
  totalSnappedPoints: ${snappedPts},
  scalpBounds: ${JSON.stringify(bounds)},
} as const;
`;
}

async function writeDebugOverlay(scalpData, zones) {
  const scalpEdge = scalpData.profile
    .filter((_, i) => i % 6 === 0)
    .flatMap((p) => [
      `<circle cx="${p.lx}" cy="${p.y}" r="2" fill="#00ff88"/>`,
      `<circle cx="${p.rx}" cy="${p.y}" r="2" fill="#00ff88"/>`,
    ])
    .join('');

  const paths = Object.entries(zones)
    .flatMap(([zone, { paths, fillRule }]) =>
      paths.map((d) => {
        const rule = fillRule ? ` fill-rule="${fillRule}"` : '';
        return `<path d="${d}" fill="${ZONE_COLORS[zone]}" stroke="#751F5E" stroke-width="3" stroke-dasharray="10 8"${rule}/>`;
      }),
    )
    .join('');

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${scalpData.width}" height="${scalpData.height}" viewBox="0 0 ${scalpData.width} ${scalpData.height}">${scalpEdge}${paths}</svg>`;
  const base = await sharp(join(root, 'public', 'man.webp')).ensureAlpha().png().toBuffer();
  const overlay = await sharp(Buffer.from(svg)).png().toBuffer();
  const out = await sharp(base).composite([{ input: overlay, blend: 'over' }]).png().toBuffer();
  await sharp(out).toFile(join(root, 'public', 'debug-scalp-profile.png'));
  await sharp(out).toFile(join(root, 'public', 'debug-zones.png'));
}
